package cli

import (
	"fmt"
	"github.com/spf13/cobra"
	"io"
	"sort"
)

// CLIReference is generated from the same command tree and flag definitions as help.
func CLIReference(w io.Writer, root *cobra.Command) error {
	var walk func(*cobra.Command) error
	walk = func(c *cobra.Command) error {
		if c.Hidden || c.Name() == "completion" || c.Name() == "help" {
			return nil
		}
		if _, e := fmt.Fprintf(w, "## %s\n\n%s\n\n```text\n%s\n```\n\n", c.CommandPath(), c.Short, c.UseLine()); e != nil {
			return e
		}
		c.InheritedFlags()
		flags := c.LocalFlags().FlagUsages() + c.InheritedFlags().FlagUsages()
		if flags != "" {
			if _, e := fmt.Fprintf(w, "```text\n%s```\n\n", flags); e != nil {
				return e
			}
		}
		children := c.Commands()
		sort.Slice(children, func(i, j int) bool { return children[i].Name() < children[j].Name() })
		for _, child := range children {
			if e := walk(child); e != nil {
				return e
			}
		}
		return nil
	}
	_, e := fmt.Fprintln(w, "# CLI reference\n\nGenerated by `pftw docs`. Do not edit by hand.")
	if e != nil {
		return e
	}
	return walk(root)
}

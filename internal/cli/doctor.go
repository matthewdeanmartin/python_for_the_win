package cli

import (
	"fmt"
	"github.com/matthewdeanmartin/python_for_the_win/internal/envpath"
	"github.com/matthewdeanmartin/python_for_the_win/internal/preflight"
	"github.com/matthewdeanmartin/python_for_the_win/internal/shims"
	"github.com/spf13/cobra"
	"os"
	"path/filepath"
	"strings"
)

func lookupCommand(path, name string) string {
	exts := strings.Split(os.Getenv("PATHEXT"), ";")
	if len(exts) == 0 || exts[0] == "" {
		exts = []string{".COM", ".EXE", ".BAT", ".CMD"}
	}
	for _, dir := range envpath.Split(path) {
		dir = envpath.Expand(strings.Trim(dir, `"`))
		if dir == "" {
			continue
		}
		for _, ext := range exts {
			p := filepath.Join(dir, name+strings.ToLower(ext))
			if i, e := os.Stat(p); e == nil && !i.IsDir() {
				return p
			}
		}
	}
	return "not found"
}
func (o *options) doctor(c *cobra.Command) error {
	s, e := o.load()
	if e != nil {
		return e
	}
	checks := preflight.Run(o.info, o.root, "", s, true)
	add := func(id, status, title, detail, fix string) {
		checks = append(checks, preflight.Check{ID: id, Status: status, Title: title, Detail: detail, Fix: fix})
	}
	sys, se := o.info.SystemPath()
	user, ue := o.store.Get()
	owned := preflight.Owned(o.root, s)
	if se != nil || ue != nil {
		add("path-read", "Info", "Persistent PATH information unavailable", fmt.Sprintf("system: %v; user: %v", se, ue), "")
	} else {
		path := sys.Text + ";" + user.Text
		for _, name := range []string{"python", "python3", "pip", "py"} {
			p := lookupCommand(path, name)
			status := "Info"
			if envpath.Contains(owned, filepath.Dir(p)) {
				status = "OK"
			}
			add("resolve-"+name, status, name+" on a new terminal PATH", p, "")
			current := lookupCommand(os.Getenv("PATH"), name)
			if !envpath.Equal(current, p) {
				add("current-"+name, "Info", name+" in this process PATH", current, "Open a new terminal after PATH changes.")
			}
		}
		for _, hit := range preflight.FindPythons(sys.Text, user.Text, owned, preflight.FileLookup(o.info)) {
			kind := "other Python"
			if hit.Alias {
				kind = "app execution alias"
			}
			if hit.Name == "py.exe" {
				kind = "py is a different launcher and will not see pftw Pythons; use python3.X or pftw run"
			}
			add("clash", "Info", kind+" on "+hit.Scope+" PATH", filepath.Join(hit.Dir, hit.Name), "")
		}
		for _, p := range s.Path().Added {
			if !envpath.Contains(envpath.Split(user.Text), p) {
				add("missing-path", "Warn", "Managed PATH entry is missing", p, "Run install --path first if you want PATH integration.")
			}
		}
	}
	for key := range s.Installs {
		p := filepath.Join(o.root, "versions", key, "python.exe")
		if _, e = os.Stat(p); e != nil {
			add("missing-runtime", "Warn", "Installed runtime is missing", p, "Inspect this installation before retrying installation.")
		}
	}
	dirs, _ := os.ReadDir(filepath.Join(o.root, "versions"))
	for _, d := range dirs {
		if _, ok := s.Installs[d.Name()]; !ok {
			add("orphan", "Warn", "Unregistered runtime directory", d.Name(), "Inspect it manually; pftw will not take ownership.")
		}
	}
	for _, name := range shims.Names(s) {
		if shims.Windowed(name) {
			if _, err := os.Stat(filepath.Join(o.root, "shims", "pftww.exe")); os.IsNotExist(err) {
				add("windowed-unavailable", "Info", "Windowed aliases unavailable", "This build has no pftww.exe companion", "Use the Windows release ZIP or make build output.")
				continue
			}
		}
		if _, e = os.Stat(filepath.Join(o.root, "shims", name)); e != nil {
			add("missing-shim", "Warn", "Versioned command is missing", name, "Re-run install for an installed version to regenerate commands.")
		}
	}
	expected := map[string]bool{}
	for _, n := range shims.Names(s) {
		expected[n] = true
	}
	actual, _ := os.ReadDir(filepath.Join(o.root, "shims"))
	for _, entry := range actual {
		if shims.IsName(entry.Name()) && !expected[entry.Name()] {
			add("stale-shim", "Warn", "Unexpected versioned command", entry.Name(), "Inspect the command; a managed shim is regenerated by install.")
		}
	}
	for _, dir := range []string{"staging", "trash"} {
		entries, _ := os.ReadDir(filepath.Join(o.root, dir))
		if len(entries) > 0 {
			add("leftovers", "Info", "Pending "+dir+" files", fmt.Sprintf("%d entries", len(entries)), "A mutating command attempts recovery before cleanup.")
		}
	}
	for _, name := range []string{"transaction.json", "path-transaction.json"} {
		if _, e = os.Stat(filepath.Join(o.root, name)); e == nil {
			add("pending", "Warn", "Interrupted operation awaits recovery", name, "Run a mutating command to attempt recovery; keep recovery data.")
		}
	}
	_, source, e := o.client(s)
	if e != nil {
		return e
	}
	if o.json {
		return o.output(c, map[string]any{"root": o.root, "source": source, "portable": s.Portable(), "checks": checks}, "")
	}
	fmt.Fprintln(c.OutOrStdout(), "Root:", o.root)
	fmt.Fprintln(c.OutOrStdout(), "Source:", source)
	for _, check := range checks {
		fmt.Fprintf(c.OutOrStdout(), "%s: %s", check.Status, check.Title)
		if check.Detail != "" {
			fmt.Fprintf(c.OutOrStdout(), " â€” %s", check.Detail)
		}
		fmt.Fprintln(c.OutOrStdout())
		if check.Fix != "" {
			fmt.Fprintln(c.OutOrStdout(), "  "+check.Fix)
		}
	}
	return nil
}
